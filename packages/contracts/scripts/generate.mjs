// Generates TypeScript types and Pydantic v2 models from the JSON Schema sources in ../schemas.
//
//   schemas/*.schema.json --(bundle)--> generated/bundle.schema.json
//                                   |--> src/generated/contracts.ts                     (json-schema-to-typescript)
//                                   '--> core-py/src/magaza_core/contracts/generated.py  (datamodel-code-generator)
import { spawnSync } from "node:child_process";
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const pkgDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = resolve(pkgDir, "../..");
const schemaDir = join(pkgDir, "schemas");
const bundlePath = join(pkgDir, "generated", "bundle.schema.json");
const tsOut = join(pkgDir, "src", "generated", "contracts.ts");
const pyOut = join(repoRoot, "packages", "core-py", "src", "magaza_core", "contracts", "generated.py");

const BANNER = "DO NOT EDIT. Generated by packages/contracts/scripts/generate.mjs from packages/contracts/schemas.";

function rewriteRefs(node) {
  if (Array.isArray(node)) return node.map(rewriteRefs);
  if (node && typeof node === "object") {
    return Object.fromEntries(
      Object.entries(node).map(([key, value]) =>
        key === "$ref" && typeof value === "string"
          ? [key, value.replace(/^[a-z-]+\.schema\.json#/, "#")]
          : [key, rewriteRefs(value)],
      ),
    );
  }
  return node;
}

export function buildBundle() {
  const defs = {};
  const files = readdirSync(schemaDir).filter((f) => f.endsWith(".schema.json")).sort();
  for (const file of files) {
    const schema = JSON.parse(readFileSync(join(schemaDir, file), "utf8"));
    for (const [name, def] of Object.entries(schema.$defs ?? {})) {
      if (defs[name]) throw new Error(`Duplicate $def "${name}" in ${file}`);
      if (def.title !== name) throw new Error(`$def "${name}" in ${file} must have title "${name}"`);
      defs[name] = rewriteRefs(def);
    }
  }
  return {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    $id: "magaza-contracts.bundle.json",
    title: "MagazaContracts",
    description: BANNER,
    type: "object",
    additionalProperties: false,
    properties: Object.fromEntries(Object.keys(defs).map((name) => [name, { $ref: `#/$defs/${name}` }])),
    $defs: defs,
  };
}

async function main() {
  const bundle = buildBundle();
  mkdirSync(dirname(bundlePath), { recursive: true });
  writeFileSync(bundlePath, JSON.stringify(bundle, null, 2) + "\n");

  const ts = await compile(bundle, "MagazaContracts", {
    bannerComment: `/* eslint-disable */\n/** ${BANNER} */`,
    additionalProperties: false,
    unreachableDefinitions: true,
    strictIndexSignatures: true,
    style: { singleQuote: false, printWidth: 110 },
  });
  mkdirSync(dirname(tsOut), { recursive: true });
  writeFileSync(tsOut, ts);

  const args = [
    "run",
    "datamodel-codegen",
    "--input", relative(repoRoot, bundlePath),
    "--input-file-type", "jsonschema",
    "--output", relative(repoRoot, pyOut),
    "--output-model-type", "pydantic_v2.BaseModel",
    "--target-python-version", "3.12",
    "--use-title-as-name",
    "--use-standard-collections",
    "--use-union-operator",
    "--enum-field-as-literal", "all",
    "--use-double-quotes",
    "--disable-timestamp",
    "--field-constraints",
    "--use-annotated",
    "--use-default",
    "--output-datetime-class", "datetime",
    "--use-schema-description",
    "--collapse-root-models",
    "--formatters", "ruff-format",
  ];
  const result = spawnSync("uv", args, { cwd: repoRoot, stdio: "inherit" });
  if (result.status !== 0) throw new Error(`datamodel-codegen failed with exit code ${result.status}`);
  console.log(`contracts: ${Object.keys(bundle.$defs).length} types -> ${relative(repoRoot, tsOut)}, ${relative(repoRoot, pyOut)}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((err) => {
    console.error(err);
    process.exit(1);
  });
}
