def _liters(v: float) -> str:
    return (f"{v:g}".replace(".", ",")) + " L"


def build(b: Builder) -> None:
    _paints(b)
    _primers(b)
    _paint_supplies(b)
    _adhesives(b)
    _hardware(b)
    _hand_tools(b)
    _power_tools(b)
    _bathroom(b)
    _cleaning(b)


